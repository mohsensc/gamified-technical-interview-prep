const pool1d = entries.filter(entry => entry.dim === 1)
const pool2d = entries.filter(entry => entry.dim === 2)

export function makeQuestion(level = 1) {
  const item = pickByLevel(entries, level)
  const index = entries.indexOf(item)
  const pool = item.dim === 1 ? pool1d : pool2d
  const recDistractors = pool.filter(entry => entry !== item).map(entry => entry.rec)
  const baseDistractors = pool.filter(entry => entry !== item).map(entry => entry.base)
  return {
    id: `recurrence-match:${index}`,
    skills: item.skills,
    tag: '📐 DP recurrence',
    summary: item.name,
    prompt: `${item.name} — define dp[i]${item.dim === 2 ? '[j]' : ''}.`,
    parts: [
      part('Recurrence?', item.rec, recDistractors, item.recWhy),
      part('Base case?', item.base, baseDistractors, item.baseWhy),
    ],
  }
}

export default {
  id: 'recurrence-match',
  title: 'Recurrence Match',
  icon: '📐',
  blurb: 'Problem in, DP recurrence and base case out.',
  skills: ['dp-1d', 'dp-2d'],
  difficulty: 'Up to Lv 6',
  modeLabel: '3 lives',
  supportsDaily: true,
  mount: (container, api) => runQuiz(container, api, {
    title: 'Recurrence Match',
    icon: '📐',
    rules: ['recurrence, then base case', 'combos multiply'],
    mode: 'lives',
    lives: 3,
    speedMs: 14000,
    seed: api.seed,
    makeQuestion,
  }),
}
